#!/usr/bin/env python3
"""Build an FW-MAME FPGA design and embed its .fwfpga in a C header for a
display app (adapted from FW-TPG's fw2/apps/tpg_fpga/gen_fwfpga_header.py).

    python tools/gen_fwfpga_header.py --name fbuf --out build-fw2/.../fbuf_fwfpga.h

Runs tools/setup.py's link step (wilifpga only builds designs under
wilifpga/designs/), then `fwfpga build <name>`, and writes the file as a byte
array with FWFPGA_NAME / _DESIGN_ID / _VERSION / _LEN / _HEADER_LEN macros.
Needs the wilifpga toolchain. --no-build embeds the existing build output.
"""
import argparse
import pathlib
import struct
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
MAGIC = b"FW2FPGA\0"
HEADER_LEN = 256


def parse_header(data):
    if len(data) < HEADER_LEN or data[:8] != MAGIC:
        sys.exit("not a .fwfpga file (bad magic)")
    manifest_len, bitstream_len = struct.unpack_from("<II", data, 12)
    if len(data) != HEADER_LEN + manifest_len + bitstream_len:
        sys.exit("bad .fwfpga length")
    name = data[56:88].split(b"\0", 1)[0].decode("ascii")
    design_id, version = struct.unpack_from("<HH", data, 216)
    return name, design_id, version


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--name", required=True)
    ap.add_argument("--out", required=True, type=pathlib.Path)
    ap.add_argument("--no-build", action="store_true")
    a = ap.parse_args()

    wilifpga = ROOT / "wilifpga"
    if not a.no_build:
        subprocess.run([sys.executable, str(ROOT / "tools" / "setup.py")], check=True, stdout=subprocess.DEVNULL)
        subprocess.run([sys.executable, "tools/fwfpga.py", "build", a.name], cwd=wilifpga, check=True)

    path = wilifpga / "build" / "designs" / a.name / f"{a.name}.fwfpga"
    data = path.read_bytes()
    name, design_id, version = parse_header(data)
    rows = [", ".join(f"0x{b:02X}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(
        f"/* Generated by tools/gen_fwfpga_header.py from {path.name} - do not edit. */\n"
        "#pragma once\n#include <stdint.h>\n\n"
        f"#define FWFPGA_NAME       \"{name}\"\n"
        f"#define FWFPGA_DESIGN_ID  {design_id}u\n"
        f"#define FWFPGA_VERSION    {version}u\n"
        f"#define FWFPGA_LEN        {len(data)}u\n"
        f"#define FWFPGA_HEADER_LEN {HEADER_LEN}u\n\n"
        "static const uint8_t FWFPGA[FWFPGA_LEN] = {\n    " + ",\n    ".join(rows) + "\n};\n")
    print(f"embedded {path} ({len(data)} bytes, {name} id {design_id} v{version}) -> {a.out}")


if __name__ == "__main__":
    main()
